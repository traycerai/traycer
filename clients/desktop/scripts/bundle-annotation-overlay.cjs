#!/usr/bin/env bun
"use strict";

/**
 * Bundles the isolated-world annotation overlay (plus perfect-freehand)
 * into a self-contained IIFE string that CDP can evaluate.
 *
 * Invoked by build-main-bundle.cjs and safe to run on its own.
 */

const { mkdirSync, writeFileSync } = require("node:fs");
const path = require("node:path");
const esbuild = require("esbuild");

const workspaceRoot = path.resolve(__dirname, "..");
const guestEntry = path.resolve(
  workspaceRoot,
  "src",
  "electron-main",
  "browser-view",
  "annotation",
  "browser-annotation-overlay-guest.ts",
);
const outFile = path.resolve(
  workspaceRoot,
  "src",
  "electron-main",
  "browser-view",
  "annotation",
  "browser-annotation-overlay-guest.generated.ts",
);

function stripIife(code) {
  let trimmed = code
    .replace(/^\uFEFF/, "")
    .trim()
    .replace(/;+\s*$/, "");
  trimmed = trimmed.replace(/^(?:["']use strict["']\s*;\s*)+/, "").trim();
  const arrow = /^\(\(\)\s*=>\s*\{([\s\S]*)\}\)\(\)$/;
  const fn = /^\(function\s*\(\)\s*\{([\s\S]*)\}\)\(\)$/;
  const match = trimmed.match(arrow) || trimmed.match(fn);
  return match === null ? trimmed : match[1];
}

function wrapAsIife(code) {
  const inner = stripIife(code).replace(/\bboot\(\);\s*$/, "return boot();");
  if (!/\breturn boot\(\);/.test(inner)) {
    throw new Error(
      "overlay guest bundle did not end with boot(); cannot propagate boot result",
    );
  }
  return '(function(){\n"use strict";' + inner + "\n})()";
}

function generate() {
  const result = esbuild.buildSync({
    absWorkingDir: workspaceRoot,
    entryPoints: [guestEntry],
    bundle: true,
    write: false,
    format: "iife",
    platform: "browser",
    target: "es2019",
    minify: false,
    legalComments: "none",
    logLevel: "silent",
  });
  const file = result.outputFiles[0];
  if (file === undefined) {
    throw new Error("overlay guest bundle produced no output");
  }
  const source = wrapAsIife(file.text);
  const header = [
    "/* eslint-disable */",
    "/**",
    " * Generated by scripts/bundle-annotation-overlay.cjs.",
    " * Do not edit. Re-run the bundler after changing the guest overlay.",
    " */",
    "",
    "export const ANNOTATION_OVERLAY_GUEST_SOURCE: string =",
  ].join("\n");
  const body = JSON.stringify(source);
  mkdirSync(path.dirname(outFile), { recursive: true });
  writeFileSync(outFile, header + "\n  " + body + ";\n", "utf8");
  return outFile;
}

if (require.main === module) {
  const dest = generate();
  console.log(
    "[desktop] bundled annotation overlay → " +
      path.relative(workspaceRoot, dest),
  );
}

module.exports = { generate };
